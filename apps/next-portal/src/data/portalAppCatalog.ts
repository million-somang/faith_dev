export function mapMiniAppsToCatalog(rawApps: RawApiMiniApp[]): LauncherCatalogItem[] {
    return rawApps
        .filter((app) => app && app.category !== 'game' && (!app.status || app.status === 'active'))
        .map((app) => {
            const visual = getUtilityVisualMeta(app.slug, app.description);
            const isPopupMiniApp = typeof app.app_url === 'string' && app.app_url.startsWith('/app/');
            const iconColor = MINIAPP_COLOR_BY_CATEGORY[app.category || ''] || 'indigo';

            return {
                catalogKey: `miniapp:${app.slug}`,
                source: isPopupMiniApp ? 'miniapp' : 'portal',
                name: app.name,
                description: visual.shortDesc || app.description || '무설치 웹 생활 도구',
                categoryLabel: visual.categoryLabel || '생활도구',
                url: app.app_url,
                slug: app.slug,
                miniAppId: app.id,
                iconType: 'image',
                iconValue: visual.image,
                iconColor,
            };
        });
}
